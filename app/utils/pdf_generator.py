def draw_pdf_star(pdf: FPDF, cx: float, cy: float, r_out: float = 1.9, r_in: float = 0.85, star_type: str = "full"):
    """
    Draw a crisp 5-pointed star shape in FPDF using vector polygon.
    star_type: 'full', 'half', or 'empty'
    """
    pts = []
    for i in range(10):
        angle = -math.pi / 2 + i * math.pi / 5
        r = r_out if i % 2 == 0 else r_in
        pts.append((cx + r * math.cos(angle), cy + r * math.sin(angle)))

    if star_type == "full":
        pdf.set_fill_color(245, 158, 11)   # Amber-500
        pdf.set_draw_color(217, 119, 6)    # Amber-600
        pdf.polygon(pts, style="DF")
    elif star_type == "half":
        # Draw background empty star
        pdf.set_fill_color(241, 245, 249)  # Slate-100
        pdf.set_draw_color(203, 213, 225)  # Slate-300
        pdf.polygon(pts, style="DF")
        # Clip left half and fill with amber
        with pdf.rect_clip(cx - r_out - 0.5, cy - r_out - 0.5, r_out + 0.5, (r_out + 0.5) * 2):
            pdf.set_fill_color(245, 158, 11)
            pdf.set_draw_color(217, 119, 6)
            pdf.polygon(pts, style="DF")
        # Re-stroke border
        pdf.set_draw_color(203, 213, 225)
        pdf.polygon(pts, style="D")
    else:  # 'empty'
        pdf.set_fill_color(241, 245, 249)  # Slate-100
        pdf.set_draw_color(203, 213, 225)  # Slate-300
        pdf.polygon(pts, style="DF")


def clean_text(text: Any) -> str:
    """
    Sanitize text to be safe for standard FPDF core fonts (latin-1 compatible).
    Replaces common Unicode typography with standard ASCII approximations.
    """
    if text is None:
        return ""
    text = str(text)

    replacements = {
        "\u2022": "-",      # Bullet
        "\u2023": "-",
        "\u25e6": "-",
        "\u2013": "-",      # En dash
        "\u2014": "--",     # Em dash
        "\u2018": "'",      # Left single quote
        "\u2019": "'",      # Right single quote
        "\u201a": ",",
        "\u201c": '"',      # Left double quote
        "\u201d": '"',      # Right double quote
        "\u201e": '"',
        "\u2026": "...",    # Ellipsis
        "\xa0": " ",        # Non-breaking space
        "\u2122": "TM",     # Trademark
        "\xae": "(R)",
        "\xa9": "(C)",
        "\u200b": "",       # Zero-width space
        "\ufeff": "",
        "\t": "    ",
        "\r\n": "\n",
        "\r": "\n",
    }
    for orig, repl in replacements.items():
        text = text.replace(orig, repl)

    # Encode to latin-1 with replacement for any unmapped symbols, then decode back
    return text.encode("latin-1", errors="replace").decode("latin-1")


def get_val(obj: Any, key: str, default: Any = None) -> Any:
    """Safely retrieve value from a dictionary or model instance attribute."""
    if obj is None:
        return default
    if isinstance(obj, dict):
        return obj.get(key, default)
    return getattr(obj, key, default)


class ResumeReportPDF(FPDF):
    """Custom FPDF generator for professional Resume Analysis PDF reports."""

    def __init__(self, candidate_name: str = "Candidate"):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.candidate_name = clean_text(candidate_name)
        self.set_auto_page_break(auto=True, margin=18)
        self.alias_nb_pages()

    def header(self):
        # Top branding banner
        self.set_fill_color(30, 41, 59)  # Slate-800
        self.rect(0, 0, 210, 14, "F")
        
        self.set_font("Helvetica", "B", 8)
        self.set_text_color(148, 163, 184)  # Slate-400
        self.set_xy(10, 3)
        self.cell(100, 8, "SMART RESUME ANALYZER  |  COMPREHENSIVE AUDIT REPORT", align="L")
        
        self.set_xy(110, 3)
        self.cell(90, 8, f"Candidate: {self.candidate_name}", align="R")
        
        # Reset position below banner
        self.set_y(18)

    def footer(self):
        self.set_y(-14)
        self.set_draw_color(226, 232, 240)
        self.line(10, self.get_y(), 200, self.get_y())
        
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(148, 163, 184)
        self.cell(95, 10, "Generated by Smart Resume Analyzer AI", align="L")
        self.cell(95, 10, f"Page {self.page_no()} of {{nb}}", align="R")

    def section_heading(self, title: str, icon_tag: str = ""):
        """Render a styled section heading banner."""
        self.ln(3)
        self.set_font("Helvetica", "B", 12)
        self.set_fill_color(241, 245, 249)  # Slate-100
        self.set_text_color(30, 41, 59)     # Slate-800
        self.set_draw_color(203, 213, 225)  # Slate-300
        
        heading_text = f"  {title.upper()}"
        self.cell(0, 8, clean_text(heading_text), border="L", fill=True, new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(79, 70, 229)    # Indigo accent border left
        self.rect(self.l_margin, self.get_y() - 8, 1.5, 8, "F")
        self.ln(2)


def generate_resume_pdf(resume: Any) -> bytes:
    """
    Generate a polished, multi-page PDF report for the given Resume instance.
    Returns bytes of the compiled PDF.
    """
    candidate_name = resume.candidate_name or "Candidate"
    pdf = ResumeReportPDF(candidate_name=candidate_name)
    pdf.add_page()

    # --- 1. HERO / CANDIDATE IDENTITY CARD ---
    pdf.set_fill_color(248, 250, 252)  # Slate-50
    pdf.set_draw_color(226, 232, 240)  # Slate-200
    start_y = pdf.get_y()
    pdf.rect(10, start_y, 190, 42, "DF")

    # Name and Title
    pdf.set_xy(14, start_y + 3)
    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(15, 23, 42)  # Slate-900
    pdf.cell(110, 8, clean_text(candidate_name), new_x="LMARGIN", new_y="NEXT")

    # Contact details
    pdf.set_x(14)
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(71, 85, 105)  # Slate-600
    contact_parts = []
    if resume.candidate_email:
        contact_parts.append(f"Email: {resume.candidate_email}")
    if resume.candidate_phone:
        contact_parts.append(f"Phone: {resume.candidate_phone}")
    if resume.candidate_location:
        contact_parts.append(f"Location: {resume.candidate_location}")
    contact_line = "  |  ".join(contact_parts) if contact_parts else "No contact details parsed"
    pdf.cell(110, 5, clean_text(contact_line), new_x="LMARGIN", new_y="NEXT")

    # File metadata
    pdf.set_x(14)
    file_info = f"File: {resume.filename} ({resume.file_type.upper()})"
    if resume.uploaded_at:
        file_info += f"  |  Analyzed: {resume.uploaded_at.strftime('%b %d, %Y')}"
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(100, 116, 139)
    pdf.cell(110, 5, clean_text(file_info), new_x="LMARGIN", new_y="NEXT")

    # Score Cards on Right Side of Hero
    ats_score = int(resume.ats_score or 0)
    comp_score = int(resume.completeness_score or 0)
    skills_count = len(resume.skills or [])

    # ATS Score Pill
    pdf.set_xy(130, start_y + 4)
    pdf.set_fill_color(238, 242, 255)  # Indigo-50
    pdf.set_draw_color(199, 210, 254)  # Indigo-200
    pdf.rect(130, start_y + 4, 30, 24, "DF")
    pdf.set_xy(130, start_y + 6)
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(67, 56, 202)    # Indigo-700
    pdf.cell(30, 6, f"{ats_score}%", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_x(130)
    pdf.set_font("Helvetica", "B", 7)
    pdf.set_text_color(99, 102, 241)
    pdf.cell(30, 4, "ATS READINESS", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_x(130)
    pdf.set_font("Helvetica", "", 6.5)
    pdf.set_text_color(100, 116, 139)
    ats_badge = "Top Tier" if ats_score >= 75 else ("Competitive" if ats_score >= 50 else "Needs Polish")
    pdf.cell(30, 4, ats_badge, align="C")

    # Completeness Score Pill
    pdf.set_xy(165, start_y + 4)
    pdf.set_fill_color(240, 253, 244)  # Emerald-50
    pdf.set_draw_color(187, 247, 208)  # Emerald-200
    pdf.rect(165, start_y + 4, 30, 24, "DF")
    pdf.set_xy(165, start_y + 6)
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(21, 128, 61)     # Emerald-700
    pdf.cell(30, 6, f"{comp_score}%", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_x(165)
    pdf.set_font("Helvetica", "B", 7)
    pdf.set_text_color(16, 185, 129)
    pdf.cell(30, 4, "COMPLETENESS", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_x(165)
    pdf.set_font("Helvetica", "", 6.5)
    pdf.set_text_color(100, 116, 139)
    pdf.cell(30, 4, f"{skills_count} Skills Parsed", align="C")

    # 5-Star Rating Pill right below ATS Score & Completeness pills
    star_rating, full_stars, half_star, empty_stars = compute_star_rating(resume.ats_score)
    rating_x = 130
    rating_y = start_y + 30.5
    rating_w = 65
    rating_h = 7.5
    pdf.set_xy(rating_x, rating_y)
    pdf.set_fill_color(255, 251, 235)  # Amber-50
    pdf.set_draw_color(251, 191, 36)   # Amber-300
    pdf.rect(rating_x, rating_y, rating_w, rating_h, "DF")

    # Draw star shapes inside the rating pill
    star_start_x = rating_x + 4.5
    star_cy = rating_y + 3.75
    r_out = 1.9
    r_in = 0.85
    spacing = 4.4

    cur_x = star_start_x
    for _ in range(full_stars):
        draw_pdf_star(pdf, cur_x, star_cy, r_out=r_out, r_in=r_in, star_type="full")
        cur_x += spacing
    if half_star:
        draw_pdf_star(pdf, cur_x, star_cy, r_out=r_out, r_in=r_in, star_type="half")
        cur_x += spacing
    for _ in range(empty_stars):
        draw_pdf_star(pdf, cur_x, star_cy, r_out=r_out, r_in=r_in, star_type="empty")
        cur_x += spacing

    # Text next to stars: e.g. "(4.2 / 5)"
    pdf.set_xy(cur_x + 1.5, rating_y + 1)
    pdf.set_font("Helvetica", "B", 7.5)
    pdf.set_text_color(180, 83, 9)     # Amber-700
    pdf.cell(rating_w - (cur_x - rating_x) - 2, 5.5, f"({star_rating} / 5)", align="L")

    pdf.set_y(start_y + 46)

    # --- 2. BENCHMARK JOB ROLE MATCHES ---
    pdf.section_heading("Benchmark Job Role Matches & Skill Alignment")

    job_matches = list(resume.job_matches or [])
    if job_matches:
        # Table Header
        pdf.set_fill_color(224, 231, 255)  # Light Indigo
        pdf.set_text_color(30, 41, 59)
        pdf.set_font("Helvetica", "B", 8)
        pdf.cell(50, 7, "  Job Role & Domain", border=1, fill=True)
        pdf.cell(20, 7, "Match %", border=1, align="C", fill=True)
        pdf.cell(60, 7, "Matched Skills", border=1, fill=True)
        pdf.cell(60, 7, "Missing Skills Gap", border=1, fill=True, new_x="LMARGIN", new_y="NEXT")

        pdf.set_font("Helvetica", "", 7.5)
        for i, match in enumerate(job_matches[:5]):
            pct = round(float(get_val(match, "match_percentage") or 0.0), 1)
            row_fill = (i % 2 == 1)
            if row_fill:
                pdf.set_fill_color(248, 250, 252)
            else:
                pdf.set_fill_color(255, 255, 255)

            # Role Title
            job_title = get_val(match, "job_title") or "Target Role"
            domain = get_val(match, "domain") or "General"
            exp_level = get_val(match, "experience_level") or "Mid"
            matched_skills = get_val(match, "matched_skills") or []
            missing_skills = get_val(match, "missing_skills") or []

            matched_str = ", ".join(matched_skills[:8]) if matched_skills else "None detected"
            missing_str = ", ".join(missing_skills[:8]) if missing_skills else "No major gap"

            # Draw Row
            curr_y = pdf.get_y()
            if curr_y > 250:
                pdf.add_page()
                curr_y = pdf.get_y()

            role_label = f"{job_title} ({exp_level})" if exp_level else job_title
            pdf.cell(50, 6, clean_text(role_label), border="LR", fill=row_fill)
            
            # Match score colored text
            if pct >= 75:
                pdf.set_text_color(16, 185, 129)
            elif pct >= 50:
                pdf.set_text_color(59, 130, 246)
            else:
                pdf.set_text_color(217, 119, 6)
            pdf.set_font("Helvetica", "B", 8)
            pdf.cell(20, 6, f"{pct}%", border="LR", align="C", fill=row_fill)

            pdf.set_font("Helvetica", "", 7)
            pdf.set_text_color(51, 65, 85)
            pdf.cell(60, 6, clean_text(matched_str[:45] + ("..." if len(matched_str) > 45 else "")), border="LR", fill=row_fill)
            
            pdf.set_text_color(225, 29, 72)  # Rose/Red for missing skills
            pdf.cell(60, 6, clean_text(missing_str[:45] + ("..." if len(missing_str) > 45 else "")), border="LR", fill=row_fill, new_x="LMARGIN", new_y="NEXT")
            pdf.set_text_color(30, 41, 59)

        # Bottom border for table
        pdf.cell(190, 0, "", border="T", new_x="LMARGIN", new_y="NEXT")
    else:
        pdf.set_font("Helvetica", "I", 9)
        pdf.set_text_color(100, 116, 139)
        pdf.cell(0, 6, "No benchmark matches calculated for this resume.", new_x="LMARGIN", new_y="NEXT")

    pdf.ln(3)

    # --- 3. ATS FEEDBACK & OPTIMIZATION AUDIT ---
    pdf.section_heading("ATS Optimization & Content Breakdown")

    ats_data = resume.ats_feedback or {}
    strengths = ats_data.get("strengths", [])
    warnings = ats_data.get("warnings", [])
    suggestions = ats_data.get("suggestions", [])
    stats = ats_data.get("stats", {})

    # Key Statistics Bar
    if stats:
        pdf.set_fill_color(241, 245, 249)
        pdf.set_font("Helvetica", "", 8)
        pdf.set_text_color(51, 65, 85)
        stat_line = (
            f"Word Count: {stats.get('word_count', 0)}  |  "
            f"Reading Time: ~{stats.get('reading_time_minutes', 1)} min  |  "
            f"Action Verbs Found: {stats.get('action_verbs_found', 0)}  |  "
            f"Quantifiable Metrics: {stats.get('metrics_found', 0)}"
        )
        pdf.cell(190, 6, clean_text(stat_line), border=1, fill=True, align="C", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(2)

    # Strengths Block
    if strengths:
        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(16, 149, 105)  # Green
        pdf.cell(0, 5, "Key Strengths:", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 8)
        pdf.set_text_color(30, 41, 59)
        for s in strengths[:4]:
            pdf.cell(5, 4.5, "-", align="R")
            pdf.cell(185, 4.5, clean_text(f" {s}"), new_x="LMARGIN", new_y="NEXT")

    # Warnings / Areas to Polish
    if warnings:
        pdf.ln(1)
        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(194, 65, 12)  # Amber
        pdf.cell(0, 5, "Areas Needing Attention:", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 8)
        pdf.set_text_color(30, 41, 59)
        for w in warnings[:4]:
            pdf.cell(5, 4.5, "!", align="R")
            pdf.cell(185, 4.5, clean_text(f" {w}"), new_x="LMARGIN", new_y="NEXT")

    # Actionable Suggestions
    if suggestions:
        pdf.ln(1)
        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(67, 56, 202)  # Indigo
        pdf.cell(0, 5, "Actionable ATS Recommendations:", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 8)
        pdf.set_text_color(30, 41, 59)
        for sg in suggestions[:4]:
            pdf.cell(5, 4.5, ">", align="R")
            pdf.cell(185, 4.5, clean_text(f" {sg}"), new_x="LMARGIN", new_y="NEXT")

    pdf.ln(3)

    # --- 4. EXTRACTED SKILLS BREAKDOWN ---
    pdf.section_heading("Extracted Domain Skills & Categories")

    skills_by_cat: Dict[str, List[str]] = {}
    for skill_item in (resume.skills or []):
        if isinstance(skill_item, dict):
            cat = skill_item.get("category", "General")
            name = skill_item.get("name")
        else:
            cat = "General"
            name = str(skill_item)
        if name:
            skills_by_cat.setdefault(cat, []).append(name)

    if skills_by_cat:
        for cat, items in skills_by_cat.items():
            if pdf.get_y() > 260:
                pdf.add_page()
            pdf.set_font("Helvetica", "B", 8)
            pdf.set_text_color(79, 70, 229)  # Indigo
            pdf.cell(45, 5, clean_text(cat + ":"), align="L")
            pdf.set_font("Helvetica", "", 8)
            pdf.set_text_color(30, 41, 59)
            items_str = ", ".join(items)
            pdf.multi_cell(145, 5, clean_text(items_str))
            pdf.ln(1)
    else:
        pdf.set_font("Helvetica", "I", 8)
        pdf.set_text_color(100, 116, 139)
        pdf.cell(0, 5, "No specific domain skills detected.", new_x="LMARGIN", new_y="NEXT")

    # --- 5. PARSED EXPERIENCE & EDUCATION ---
    if resume.experience or resume.education:
        if pdf.get_y() > 230:
            pdf.add_page()
        pdf.section_heading("Parsed Profile Sections")

        # Experience
        if resume.experience:
            pdf.set_font("Helvetica", "B", 9)
            pdf.set_text_color(30, 41, 59)
            pdf.cell(0, 5, "Work Experience:", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 8)
            for exp in resume.experience[:4]:
                if isinstance(exp, dict):
                    title = exp.get("title") or exp.get("role") or "Role"
                    company = exp.get("company") or ""
                    duration = exp.get("duration") or exp.get("dates") or ""
                    header_str = f"- {title}" + (f" at {company}" if company else "") + (f" ({duration})" if duration else "")
                    pdf.set_font("Helvetica", "B", 8)
                    pdf.set_text_color(51, 65, 85)
                    pdf.cell(0, 4.5, clean_text(header_str), new_x="LMARGIN", new_y="NEXT")
                    
                    desc = exp.get("description") or exp.get("details")
                    if desc:
                        pdf.set_font("Helvetica", "", 7.5)
                        pdf.set_text_color(100, 116, 139)
                        pdf.set_x(15)
                        pdf.multi_cell(180, 4, clean_text(str(desc)[:220] + ("..." if len(str(desc)) > 220 else "")))
                elif isinstance(exp, str):
                    pdf.cell(0, 4.5, clean_text(f"- {exp[:100]}"), new_x="LMARGIN", new_y="NEXT")

        # Education
        if resume.education:
            pdf.ln(1)
            if pdf.get_y() > 250:
                pdf.add_page()
            pdf.set_font("Helvetica", "B", 9)
            pdf.set_text_color(30, 41, 59)
            pdf.cell(0, 5, "Education:", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 8)
            for edu in resume.education[:3]:
                if isinstance(edu, dict):
                    deg = edu.get("degree") or "Degree"
                    inst = edu.get("institution") or edu.get("school") or ""
                    year = edu.get("year") or edu.get("graduation_year") or ""
                    line = f"- {deg}" + (f", {inst}" if inst else "") + (f" ({year})" if year else "")
                    pdf.cell(0, 4.5, clean_text(line), new_x="LMARGIN", new_y="NEXT")
                elif isinstance(edu, str):
                    pdf.cell(0, 4.5, clean_text(f"- {edu[:100]}"), new_x="LMARGIN", new_y="NEXT")

    # --- 6. TARGETED LEARNING & SKILL RECOMMENDATIONS ---
    recommendations = list(resume.recommendations or [])
    if recommendations:
        if pdf.get_y() > 230:
            pdf.add_page()
        pdf.section_heading("Recommended Next Steps & Learning Paths")

        for r in recommendations[:6]:
            if pdf.get_y() > 255:
                pdf.add_page()

            skill = get_val(r, "skill_name") or get_val(r, "title") or "Recommended Skill"
            target_role = get_val(r, "target_job_role") or ""
            priority = (get_val(r, "priority") or "Medium").upper()
            category = get_val(r, "category") or "Skill"
            resources = get_val(r, "resources") or []

            pri_color = (225, 29, 72) if priority == "HIGH" else (59, 130, 246)
            pdf.set_font("Helvetica", "B", 8)
            pdf.set_text_color(*pri_color)
            pdf.cell(18, 5, f"[{priority}]", align="L")

            pdf.set_font("Helvetica", "B", 8)
            pdf.set_text_color(30, 41, 59)
            heading_title = f"{skill}" + (f" - Target: {target_role}" if target_role else "") + f" ({category})"
            pdf.cell(0, 5, clean_text(heading_title), new_x="LMARGIN", new_y="NEXT")

            desc = get_val(r, "description")
            if desc:
                pdf.set_font("Helvetica", "", 7.5)
                pdf.set_text_color(100, 116, 139)
                pdf.set_x(15)
                pdf.multi_cell(180, 4, clean_text(str(desc)[:200]))
            elif resources:
                resource_snippets = []
                for res in resources[:2]:
                    if isinstance(res, dict):
                        res_title = res.get("title") or "Course"
                        res_platform = res.get("platform") or ""
                        resource_snippets.append(f"{res_title} ({res_platform})" if res_platform else res_title)
                if resource_snippets:
                    pdf.set_font("Helvetica", "", 7.5)
                    pdf.set_text_color(100, 116, 139)
                    pdf.set_x(15)
                    pdf.cell(0, 4.5, clean_text("Key Resources: " + " | ".join(resource_snippets)), new_x="LMARGIN", new_y="NEXT")

    return bytes(pdf.output())
